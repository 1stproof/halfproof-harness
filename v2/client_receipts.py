"""Content-free receipts and tool fencing for pinned Qwen 0.24.6.

The receipt overlay changes telemetry only; a separate scheduler guard enforces
the one-way report lock. Neither changes request parameters or supplies reasoning.
Both are mounted over read-only modules in the worker namespace. Receipt
IDs are generated by the gateway and never included in model-visible content.
"""
import hashlib
from pathlib import Path

MODULE = 'chunks/loggingContentGenerator-W77MU6MT.js'
SOURCE_SHA256 = '7004ba1561fd9e9af061959b2715e662257b17e16b43ebc973a1e3fa8821f0d1'
TOOL_MODULE = 'chunks/chunk-4DAVFJGK.js'
TOOL_SHA256 = '11e13080890915bb61649ba64d1f8b0fc0b42838f0f9ae8dc51281a44630da67'


def instrument(source):
    if hashlib.sha256(source).hexdigest() != SOURCE_SHA256:
        raise ValueError('unqualified Qwen receipt module')
    text = source.decode('utf-8')
    # The generator has yielded every chunk and its caller has asked for EOF.
    stream = 'streamCompleted=true;refreshLateUsageMetadata();'
    replacement = ('streamCompleted=true;if(!abortedBeforeStreamCompletion&&firstResponseId)'
                   'process.stdout.write(JSON.stringify({type:"harness_consumed",'
                   'response_id:firstResponseId,model,finish_reasons:[...finishReasons.values()]})+"\\n");'
                   'refreshLateUsageMetadata();')
    # Includes internal non-stream calls, which need no subsequent public turn.
    single = 'responseCompleted=true;const durationMs=Date.now()-startTime;'
    single_replacement = ('responseCompleted=true;if(!abortedBeforeResponseCompletion&&result.responseId)'
                          'process.stdout.write(JSON.stringify({type:"harness_consumed",'
                          'response_id:result.responseId,model:req.model,'
                          'finish_reasons:(result.candidates??[]).map(c=>c.finishReason)})+"\\n");'
                          'const durationMs=Date.now()-startTime;')
    for old, new in ((stream, replacement), (single, single_replacement)):
        if text.count(old) != 1:
            raise ValueError('ambiguous Qwen receipt seam')
        text = text.replace(old, new)
    return text.encode('utf-8')


def mount_overlay(command, control, client_root=None):
    """Return a namespace command with an immutable telemetry-only overlay."""
    client_root = client_root or Path.home()/'.local/qwen-npm/lib/node_modules/@qwen-code/qwen-code'
    source = client_root/MODULE
    namespace_root = Path.home()/'.local/qwen-npm/lib/node_modules/@qwen-code/qwen-code'
    target = control/'qwen-consumption.js'
    target.write_bytes(instrument(source.read_bytes()))
    target.chmod(0o444)
    command = list(command)
    index = command.index('--chdir')
    tool_source = client_root/TOOL_MODULE
    tool_target = control/'qwen-tool-fence.js'
    tool_target.write_bytes(instrument_tools(tool_source.read_bytes()))
    tool_target.chmod(0o444)
    command[index:index] = ['--ro-bind', str(target), str(namespace_root/MODULE),
                            '--ro-bind', str(tool_target), str(namespace_root/TOOL_MODULE)]
    return command


def instrument_tools(source):
    """Check the host's read-only one-way lock immediately before CLI dispatch.

    Both foreground and nested CLI scheduler invocation paths are guarded.
    Already-running tools retain their original bound and are reaped at handover.
    The capability file is outside model-writable roots; missing policy denies.
    """
    if hashlib.sha256(source).hexdigest() != TOOL_SHA256:
        raise ValueError('unqualified Qwen tool dispatcher')
    text = source.decode('utf-8')
    for arguments in (
        'execSignal,liveOutputCallback,shellExecutionConfig,setPidCallback,setPromoteAbortControllerCallback,canPromoteForegroundShell',
        'execSignal,liveOutputCallback,shellExecutionConfig',
    ):
        old = '()=>invocation.execute('+arguments+')'
        new = ('()=>{const p=JSON.parse(__harnessReadPolicy("/harness-control/runtime-capabilities.json","utf8"));'
               'if(p.locked&&p.capability_role==="research")throw new Error("Research tools fenced by report lock");'
               'return invocation.execute('+arguments+')}')
        if text.count(old) != 1:
            raise ValueError('ambiguous Qwen tool dispatcher')
        text = text.replace(old,new)
    return ('import {readFileSync as __harnessReadPolicy} from "node:fs";\n'+text).encode('utf-8')
